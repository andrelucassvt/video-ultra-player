import 'package:flutter/foundation.dart';

/// An immutable descriptor for a picture-in-picture video layer composited
/// over the main timeline, identical in the preview and the exported MP4.
///
/// The layer is visible on the timeline in `[start, start + duration)`,
/// clamped by the total timeline duration. [trimStart] and [trimEnd] define
/// the window inside the source file; [trimEnd] is an absolute point in the
/// source (not a duration) and `null` means "until the end of the source" —
/// [NativeTimelinePlayer.addVideoLayer] returns the layer with it resolved.
///
/// [x] and [y] are the center of the layer in normalized frame coordinates
/// (`(0, 0)` is the top-left corner, `(1, 1)` the bottom-right).
/// [widthFraction] is the layer width as a fraction of the frame width.
/// [heightFraction] is the height as a fraction of the frame height; when
/// `null` the height follows the source aspect ratio, otherwise width and
/// height are independent and the video is stretched to fill the box.
///
/// Layers are video-only: their audio is never mixed. The order of the
/// layers is their z-order — later layers are drawn on top of earlier ones,
/// all of them above the main video and below text overlays and captions.
@immutable
class TimelineVideoLayer {
  /// Creates a [TimelineVideoLayer].
  ///
  /// [x] and [y] must be in `[0.0, 1.0]`; [widthFraction] must be in
  /// `[0.1, 1.0]`; [heightFraction], when set, must be in `[0.05, 1.0]`;
  /// [opacity] must be in `[0.0, 1.0]`.
  const TimelineVideoLayer({
    required this.id,
    required this.path,
    required this.start,
    this.trimStart = Duration.zero,
    this.trimEnd,
    this.x = 0.5,
    this.y = 0.5,
    this.widthFraction = 0.5,
    this.heightFraction,
    this.opacity = 1.0,
    this.sourceWidth,
    this.sourceHeight,
  }) : assert(x >= 0.0 && x <= 1.0),
       assert(y >= 0.0 && y <= 1.0),
       assert(widthFraction >= 0.1 && widthFraction <= 1.0),
       assert(
         heightFraction == null ||
             (heightFraction >= 0.05 && heightFraction <= 1.0),
       ),
       assert(opacity >= 0.0 && opacity <= 1.0);

  /// Creates a [TimelineVideoLayer] from a channel map (durations in ms).
  factory TimelineVideoLayer.fromJson(Map<dynamic, dynamic> json) {
    final trimEndMs = json['trimEndMs'] as num?;
    return TimelineVideoLayer(
      id: json['id'] as String,
      path: json['path'] as String,
      start: Duration(milliseconds: (json['startMs'] as num).toInt()),
      trimStart: Duration(
        milliseconds: (json['trimStartMs'] as num? ?? 0).toInt(),
      ),
      trimEnd: trimEndMs == null
          ? null
          : Duration(milliseconds: trimEndMs.toInt()),
      x: (json['x'] as num? ?? 0.5).toDouble(),
      y: (json['y'] as num? ?? 0.5).toDouble(),
      widthFraction: (json['widthFraction'] as num? ?? 0.5).toDouble(),
      heightFraction: (json['heightFraction'] as num?)?.toDouble(),
      opacity: (json['opacity'] as num? ?? 1.0).toDouble(),
      sourceWidth: (json['sourceWidth'] as num?)?.toInt(),
      sourceHeight: (json['sourceHeight'] as num?)?.toInt(),
    );
  }

  /// Unique identifier generated by the app, used to update or remove the
  /// layer.
  final String id;

  /// Absolute path to the video file.
  final String path;

  /// Start of the layer on the timeline.
  final Duration start;

  /// Offset inside the source where the layer starts playing.
  final Duration trimStart;

  /// Absolute end point inside the source, or `null` for the source end.
  final Duration? trimEnd;

  /// Center of the layer in normalized frame coordinates in `[0.0, 1.0]`.
  final double x;

  /// Center of the layer in normalized frame coordinates in `[0.0, 1.0]`.
  final double y;

  /// Width of the layer as a fraction of the frame width, in `[0.1, 1.0]`.
  final double widthFraction;

  /// Height of the layer as a fraction of the frame height, or `null` to keep
  /// the source aspect ratio (no stretching).
  final double? heightFraction;

  /// Opacity of the layer in `[0.0, 1.0]`.
  final double opacity;

  /// Displayed width of the source in pixels (after rotation). Read-only:
  /// filled by the native side in the [NativeTimelinePlayer.addVideoLayer]
  /// response and never sent back.
  final int? sourceWidth;

  /// Displayed height of the source in pixels (after rotation). Read-only,
  /// see [sourceWidth].
  final int? sourceHeight;

  /// Length of the layer on the timeline, or `null` while [trimEnd] is
  /// unresolved.
  Duration? get duration {
    final end = trimEnd;
    return end == null ? null : end - trimStart;
  }

  /// Serialises this layer for the method channel. Durations are expressed in
  /// milliseconds; [trimEnd] is omitted when `null`. [sourceWidth] and
  /// [sourceHeight] are native-owned and never serialised.
  Map<String, dynamic> toJson() => <String, dynamic>{
    'id': id,
    'path': path,
    'startMs': start.inMilliseconds,
    'trimStartMs': trimStart.inMilliseconds,
    if (trimEnd != null) 'trimEndMs': trimEnd!.inMilliseconds,
    'x': x,
    'y': y,
    'widthFraction': widthFraction,
    if (heightFraction != null) 'heightFraction': heightFraction,
    'opacity': opacity,
  };

  /// Returns a copy with the given fields replaced.
  TimelineVideoLayer copyWith({
    String? id,
    String? path,
    Duration? start,
    Duration? trimStart,
    Duration? trimEnd,
    double? x,
    double? y,
    double? widthFraction,
    double? heightFraction,
    double? opacity,
    int? sourceWidth,
    int? sourceHeight,
  }) => TimelineVideoLayer(
    id: id ?? this.id,
    path: path ?? this.path,
    start: start ?? this.start,
    trimStart: trimStart ?? this.trimStart,
    trimEnd: trimEnd ?? this.trimEnd,
    x: x ?? this.x,
    y: y ?? this.y,
    widthFraction: widthFraction ?? this.widthFraction,
    heightFraction: heightFraction ?? this.heightFraction,
    opacity: opacity ?? this.opacity,
    sourceWidth: sourceWidth ?? this.sourceWidth,
    sourceHeight: sourceHeight ?? this.sourceHeight,
  );

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is TimelineVideoLayer &&
          id == other.id &&
          path == other.path &&
          start == other.start &&
          trimStart == other.trimStart &&
          trimEnd == other.trimEnd &&
          x == other.x &&
          y == other.y &&
          widthFraction == other.widthFraction &&
          heightFraction == other.heightFraction &&
          opacity == other.opacity &&
          sourceWidth == other.sourceWidth &&
          sourceHeight == other.sourceHeight;

  @override
  int get hashCode => Object.hash(
    id,
    path,
    start,
    trimStart,
    trimEnd,
    x,
    y,
    widthFraction,
    heightFraction,
    opacity,
    sourceWidth,
    sourceHeight,
  );
}
